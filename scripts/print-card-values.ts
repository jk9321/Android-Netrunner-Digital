/**
 * The every-card value audit as a Markdown table: how the AI prices each
 * card, and its numbers at the start of a game (Jeff).
 *
 *   npx vite-node scripts/print-card-values.ts > card-values.md
 */
import { ALL_CARDS, createInitialGameState } from '../src/core';
import { DECKS, deckGameSetup } from '../src/data/decks';
import { CARD_PROFILES, payoutWorth, turnsLeft } from '../src/ai/cardProfiles';
import { CARD_VALUES } from '../src/ai/cardValues';
import { COUNTER_WORTH } from '../src/ai/counterValues';
import { moneyOpGain } from '../src/ai/corpAI';
import { COUNTERS_PRICED_ELSEWHERE, valueSources } from '../src/ai/valueAudit';
import { createCardInstance } from '../src/core/engine/gameState';

const state = createInitialGameState(deckGameSetup(1, DECKS.find(d => d.side === 'corp')!, DECKS.find(d => d.side === 'runner')!));
const fmt = (n: number) => (Math.round(n * 100) / 100).toString();

const rows: string[] = [];
for (const def of [...ALL_CARDS].sort((a, b) => a.side_code.localeCompare(b.side_code) || a.type_code.localeCompare(b.type_code) || a.title.localeCompare(b.title))) {
  const numbers: string[] = [];
  const hand = CARD_VALUES[def.code];
  if (hand?.keep !== undefined) numbers.push(`keep ${hand.keep}`);
  if (hand?.econ !== undefined) numbers.push(`econ ${hand.econ}`);
  if (hand?.upgrade) numbers.push(`upgrade ${hand.upgrade.join('/')}`);
  if (hand?.rig !== undefined) numbers.push(`rig ${hand.rig}`);
  if (hand?.draws !== undefined) numbers.push(`draws ${hand.draws}`);
  const profile = CARD_PROFILES[def.code];
  if (profile) numbers.push(`pays out ${fmt(payoutWorth(profile, turnsLeft(state)))} at the start`);
  const counters = COUNTER_WORTH[def.code];
  if (counters) {
    const card = createCardInstance(state, def.code);
    for (const [type, worth] of Object.entries(counters)) numbers.push(`${type} counter ${fmt(worth!(state, card))}`);
  }
  const gain = moneyOpGain(def.code);
  if (gain !== undefined) numbers.push(`gains ${gain}`);
  if (COUNTERS_PRICED_ELSEWHERE[def.code]) numbers.push(COUNTERS_PRICED_ELSEWHERE[def.code].split(': ')[1]);
  rows.push(`| ${def.side_code} | ${def.type_code} | ${def.title} (${def.code}) | ${valueSources(def).join('; ')} | ${numbers.join('; ')} |`);
}
console.log(`# How the AI values every card\n\n${ALL_CARDS.length} cards. Generated by scripts/print-card-values.ts.\n`);
console.log('| Side | Type | Card | Valued by | Numbers |\n| --- | --- | --- | --- | --- |');
console.log(rows.join('\n'));
